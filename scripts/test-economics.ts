import assert from 'node:assert/strict';
import { once } from 'node:events';
import { randomUUID } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { existsSync, unlinkSync } from 'node:fs';
import { simulateEconomics, economicsDefaults } from '../server/economicsEngine';
process.env.NODE_ENV = 'test';
const liveHelios = process.argv.includes('--live-helios');
if (!liveHelios) process.env.GEMINI_API_KEY = '';
const file = join(tmpdir(), `economics-${randomUUID()}.json`); process.env.SOLARIS_DATA_FILE = file;
const { app } = await import('../server/index');
const { newProperty, db, addMembership, createSession } = await import('../server/businessStore');
let passed = 0; const pass = (name: string) => { passed++; console.log(`PASS ${name}`); };
const p = newProperty('test-org');
const defaults = { ...economicsDefaults(p), tenantShare: 0 };
const r = simulateEconomics(p, defaults);
assert.equal(r.generation, 24000); assert.equal(r.selfUse, 21600); assert.equal(r.avoided, 194400);
assert.equal(r.annualGross, 2332800); assert.equal(r.annualNet, 2152800); assert.equal(r.capex, 9000000);
assert.ok(Math.abs(r.plantPayback! - 4.180602) < 0.00001); pass('Reference 200 kWp / ₹90 lakh outputs reproduce exactly');
for (const capacityKwp of [0, 100, 150, 200, 250, 2000]) {
  const result = simulateEconomics(p, { ...defaults, capacityKwp });
  assert.equal(result.generation, result.selfUse + result.exported);
  assert.equal(result.load, result.selfUse + result.imported);
  assert.ok(result.selfUse <= result.generation && result.imported >= 0 && result.exported >= 0);
  assert.equal(result.before.fixed, result.after.fixed); assert.equal(result.before.demand, result.after.demand);
}
pass('Capacity accounting balances, nonnegative imports/exports, fixed/demand unchanged');
const shared = simulateEconomics(p, { ...defaults, tenantShare: 50 });
assert.equal(shared.allocated, shared.pool);
assert.equal(Math.round(shared.tenants.reduce((s, t) => s + t.benefit, 0) * 100), Math.round(shared.pool * 100));
assert.ok(shared.retained < r.retained); assert.ok(shared.investorPayback! > r.investorPayback!);
assert.equal(shared.retained + shared.tenantAnnual, shared.annualNet);
assert.ok(shared.tenantAnnual <= shared.annualNet); pass('Sharing conserves pool and reduces retained benefit without double counting');
const negative = simulateEconomics(p, { ...defaults, annualMaintenance: 99999999, tenantShare: 100 });
assert.equal(negative.investorPayback, null); assert.equal(negative.pool, 0);
assert.equal(negative.irr, null); pass('Negative returns never produce positive payback or tenant distributions');
const absent = simulateEconomics(p, { ...defaults, period: '2026-01', tenantShare: 50 });
assert.equal(absent.pool, 0); assert.ok(absent.tenants.every(t => t.usage === 0)); pass('Missing submeter periods never borrow private readings or fabricate benefits');
assert.throws(() => simulateEconomics(p, { ...defaults, tenantShare: 101 }));
assert.throws(() => simulateEconomics(p, { ...defaults, capacityKwp: NaN }));
assert.throws(() => simulateEconomics(p, { ...defaults, period: 'invalid' })); pass('Invalid inputs rejected');
assert.equal(r.cashflow[0].investor, -9000000); assert.equal(r.cashflow[1].investor, -9000000 + r.retained);
assert.ok(Number.isFinite(r.npv) && r.irr !== null); pass('Cash flow begins at negative CAPEX and NPV/IRR derive from retained cash flows');
const fullyShared = simulateEconomics(p, { ...defaults, tenantShare: 100 });
assert.equal(fullyShared.retained, 0); assert.equal(fullyShared.investorPayback, null);
assert.equal(fullyShared.cashflow.at(-1)!.investor, -fullyShared.capex);
const exportScenario = simulateEconomics(p, { ...defaults, capacityKwp: 2000, exportRate: 100 });
assert.ok(exportScenario.after.total >= 0); assert.ok(exportScenario.exportValue <= exportScenario.after.energy + exportScenario.after.demand + exportScenario.after.fixed);
assert.equal(exportScenario.annualGross, (exportScenario.before.total - exportScenario.after.total) * 12);
const expectedNpv = -r.capex + Array.from({ length: 25 }, (_, n) => r.retained / 1.1 ** (n + 1)).reduce((a, b) => a + b, 0);
assert.ok(Math.abs(r.npv - expectedNpv) < 0.01);
const irrNpv = -r.capex + Array.from({ length: 25 }, (_, n) => r.retained / (1 + r.irr! / 100) ** (n + 1)).reduce((a, b) => a + b, 0);
assert.ok(Math.abs(irrNpv) < 0.01); pass('Zero retained flow, settlement caps, independent NPV and IRR reconciliation');
const server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
const address = server.address(); assert(address && typeof address !== 'string');
const call = async (path: string, token?: string, method = 'GET', body?: unknown, status = 200) => {
  const response = await fetch(`http://127.0.0.1:${address.port}/api${path}`, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  const data = await response.json(); assert.equal(response.status, status, `${path}: ${JSON.stringify(data)}`); return data;
};
try {
  const owner = await call('/auth/demo', undefined, 'POST', { workspace: 'commercial' }, 201);
  const other = await call('/auth/demo', undefined, 'POST', { workspace: 'commercial' }, 201);
  const tenant = await call('/auth/demo', undefined, 'POST', { workspace: 'commercial', persona: 'tenant' }, 201);
  const home = await call('/auth/demo', undefined, 'POST', { workspace: 'household' }, 201);
  const property = (await call('/business/properties', owner.token)).properties[0];
  const root = `/business/properties/${property.id}/economics`;
  const input = (await call(`${root}/defaults`, owner.token)).inputs;
  const sim = await call(`${root}/simulate`, owner.token, 'POST', { inputs: input });
  assert.equal(sim.comparisons.length, 4); assert.equal(sim.result.propertyId, property.id);
  await call(`${root}/simulate`, undefined, 'POST', { inputs: input }, 401);
  await call(`${root}/simulate`, other.token, 'POST', { inputs: input }, 404);
  await call(`${root}/defaults`, home.token, 'GET', undefined, 403);
  await call(`${root}/defaults`, tenant.token, 'GET', undefined, 404);
  const tenantProperty = (await call('/business/properties', tenant.token)).properties[0];
  await call(`/business/properties/${tenantProperty.id}/economics/defaults`, tenant.token, 'GET', undefined, 403);
  pass('Simulation requires authentication; other mall, residential and tenant access denied');
  const v1 = (await call(`${root}/scenarios/save`, owner.token, 'POST', { name: 'Reference', inputs: input }, 201)).scenario;
  const v2 = (await call(`${root}/scenarios/save`, owner.token, 'POST', { name: 'Reference', inputs: { ...input, tenantShare: 75 } }, 201)).scenario;
  assert.equal(v1.version, 1); assert.equal(v2.version, 2); assert.ok(v2.result.retained < v1.result.retained);
  assert.equal((await call(`${root}/scenarios`, owner.token)).scenarios.length, 2);
  assert.equal((await call(`${root}/scenarios/${v1.id}`, owner.token)).scenario.result.capex, 9000000);
  const otherP = (await call('/business/properties', other.token)).properties[0];
  await call(`/business/properties/${otherP.id}/economics/scenarios/${v1.id}`, other.token, 'GET', undefined, 404);
  pass('Immutable scenario versions persist and cannot be read across properties');
  const explain = await call(`${root}/chart-explanation`, owner.token, 'POST', { simulationId: sim.simulationId, chart: 'payback' });
  assert.equal(explain.mode, liveHelios ? 'gemini' : 'calculation-fallback');
  if (!liveHelios) assert.ok(explain.answer.includes('2152800'));
  else { assert.ok(explain.answer.trim().length > 20); console.log('PASS Live Gemini explained an authorised synthetic Economics Studio result'); }
  await call(`/business/properties/${otherP.id}/economics/chart-explanation`, other.token, 'POST', { simulationId: sim.simulationId, chart: 'payback' }, 404);
  await call(`${root}/chart-explanation`, owner.token, 'POST', { simulationId: sim.simulationId, chart: 'tenants', shopId: 'invalid' }, 404);
  pass('Helios retrieves server result and rejects foreign simulation IDs and nonexistent shops');
  const account = { ...db.accounts.find(a => a.id === owner.account.id)!, id: randomUUID(), commercialRole: 'facility_manager' as const };
  db.accounts.push(account); addMembership(account, property.id); const manager = createSession(account);
  await call(`${root}/simulate`, manager, 'POST', { inputs: input });
  await call(`${root}/scenarios/save`, manager, 'POST', { name: 'Denied', inputs: input }, 403);
  pass('Facility manager may explore but existing owner-only write policy is preserved');
  await call('/residential/state', home.token, 'PUT', { data: { profile: { marker: 'unchanged' } } });
  assert.equal((await call('/residential/state', home.token)).data.profile.marker, 'unchanged');
  pass('Residential state flow remains functional');
} finally { await new Promise<void>(resolve => server.close(() => resolve())); if (existsSync(file)) unlinkSync(file); }
console.log(`${passed} Economics Studio checks passed`);

